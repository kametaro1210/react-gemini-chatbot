
/* 
    アプリ全体の他のファイル（APIリポジトリやコンポーネント等）で
    ユーザー情報を共通の型として再利用できるようにするため、
    クラスを外部へ公開する

    【注意事項】
    パスワードはデータベース上に保存されていますが、セキュリティ上の理由および
    フロントエンド側で保持・使用する必要がないため、意図的にこのエンティティには含めていません。
*/

export class User {
    // ユーザー固有の識別IDを文字列型で定義する
    id!: string;

    // ユーザーのメールアドレスを文字列型で定義する
    email!: string;

    // ユーザーの名前を文字列型で定義する
    name!: string;

    // インスタンス化する際に渡されたデータを、各プロパティに自動で割り当てる
    constructor(data: User) {
        // 渡ってきたデータのプロパティを、このクラスのインスタンスにまとめてコピーする
        Object.assign(this, data);
    }
}